library(ggplot2)
library(dplyr)
df <- read.csv("data.csv")
small <- df |> filter(x > 1) |> mutate(y = x * 2)
p <- ggplot(small, aes(x, y)) + geom_point() + ggtitle("Growth over time")
ggsave("growth.png", plot = p)
ggplot(small, aes(x)) + geom_histogram()
ggsave("histogram.pdf")
png("scatter.png")
plot(small$x, small$y, main = "Scatter")
dev.off()
plot(small$x)
